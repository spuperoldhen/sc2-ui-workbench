"""Plan or apply a workbench handoff to an explicitly chosen map copy."""
import argparse
import hashlib
import json
import os
from pathlib import Path, PureWindowsPath
import re
import stat
import tempfile
from zipfile import BadZipFile, ZipFile

SCRIPT = "Scripts/SC2WorkbenchUI.galaxy"
MARKER = b"// Generated by SC2 Dialog Workbench."
FILES = "地图文件/"
INIT = "初始化动作.txt"
LIMIT = 256 * 1024 ** 2
RULES = {
    "texture": {".dds", ".png", ".jpg", ".jpeg", ".tga", ".bmp", ".webp", ".gif", ".avif"},
    "fontFile": {".ttf", ".otf", ".woff", ".woff2"},
    "fontStyles": {".sc2style"},
    "layoutFile": {".sc2layout"},
    "localizedTextFile": {".txt"},
}


def format_json(value):
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def destination(root, relative):
    if not isinstance(relative, str) or not relative:
        raise ValueError("Empty map path")
    target = root
    for part in relative.split("/"):
        win = PureWindowsPath(part)
        if (part in {"", ".", ".."} or part.endswith((" ", ".")) or win.is_reserved()
                or re.search(r'[\\:<>"|?*\x00-\x1f]', part)):
            raise ValueError(f"Invalid map path: {relative}")
        target /= part
        if target.exists() or target.is_symlink():
            info = target.lstat()
            if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
                raise ValueError(f"Map path contains a link or reparse point: {target}")
    return target


def allowed(relative, kind):
    if kind == "galaxyScript":
        return relative == SCRIPT
    if kind not in RULES:
        return False
    name = Path(relative).name.lower()
    if kind == "localizedTextFile":
        return ("/localizeddata/" in ("/" + relative.lower()) and
                name in {"gamestrings.txt", "triggerstrings.txt", "objectstrings.txt"})
    return Path(name).suffix in RULES[kind]


def load_bundle(path, root):
    with ZipFile(path) as bundle:
        entries = bundle.infolist()
        names = [entry.filename for entry in entries]
        if len(set(name.casefold() for name in names)) != len(names):
            raise ValueError("Duplicate names in handoff")
        if sum(entry.file_size for entry in entries) > LIMIT:
            raise ValueError("Handoff exceeds 256 MiB")
        manifest = json.loads(bundle.read("ui_manifest.json"))
        if (manifest.get("format") != "sc2-ui-workbench-handoff" or
                manifest.get("version") != 1 or
                manifest.get("target", {}).get("format") != "SC2Components" or
                manifest.get("integration", {}).get("script") != SCRIPT or
                manifest.get("integration", {}).get("include") != 'include "Scripts/SC2WorkbenchUI"' or
                not manifest.get("diagnostics", {}).get("ready") or
                any(issue.get("level") == "error" for issue in manifest["diagnostics"].get("layoutChecks", []))):
            raise ValueError("Unsupported handoff or export checks failed")
        init = bundle.read(INIT).decode("utf-8")
        rows = {}
        seen = set()
        for item in manifest["files"]:
            relative, archive, kind = item["mapPath"], item["archivePath"], item["type"]
            target = destination(root, relative)
            if relative.casefold() in seen or archive != FILES + relative or not allowed(relative, kind):
                raise ValueError(f"Invalid handoff file: {relative}")
            seen.add(relative.casefold())
            if target.exists() and not target.is_file():
                raise ValueError(f"Map destination is not a file: {target}")
            contents = bundle.read(archive)
            rows[relative] = (target, contents)
        if SCRIPT not in rows or not rows[SCRIPT][1].startswith(MARKER):
            raise ValueError("Generated Galaxy script missing from handoff")
        if set(names) != {FILES + relative for relative in rows} | {"ui_manifest.json", INIT, "回导说明.txt"}:
            raise ValueError("Missing or unexpected files in handoff")
        return manifest, init, rows


def atomic_write(target, data):
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=target.parent, delete=False) as temp:
        try:
            temp.write(data)
            temp.close()
            os.replace(temp.name, target)
        finally:
            Path(temp.name).unlink(missing_ok=True)


def stage(options):
    root = options.map_copy.resolve(strict=True)
    out = options.evidence.resolve()
    if not root.is_dir() or not destination(root, "ComponentList.SC2Components").is_file():
        raise ValueError("Choose the test copy directory containing ComponentList.SC2Components")
    if root == out or root in out.parents:
        raise ValueError("--evidence must be outside the map")
    prior = {}
    if options.previous:
        receipt = json.loads(options.previous.read_text(encoding="utf-8"))
        if receipt.get("map") != str(root) or receipt.get("state") != "staged":
            raise ValueError("Previous receipt does not match this map copy")
        prior = {row["path"]: row["sha256"] for row in receipt["files"]}
    manifest, init, bundle = load_bundle(options.bundle, root)
    changes = []
    report = {"map": str(root), "state": "planned", "files": []}
    for relative, (target, new) in bundle.items():
        old = target.read_bytes() if target.is_file() else None
        action = "unchanged" if new == old else "create"
        if old is not None and old != new:
            action = "replace" if prior.get(relative) == digest(old) else "conflict"
        report["files"].append({"path": relative, "action": action, "sha256": digest(new)})
        if action in {"create", "replace"}:
            changes.append((relative, target, old, new))
    out.mkdir(parents=False, exist_ok=False)
    (out / "ui_manifest.json").write_text(format_json(manifest), encoding="utf-8")
    (out / INIT).write_text(init, encoding="utf-8")
    report_file = out / "stage-report.json"
    report_file.write_text(format_json(report), encoding="utf-8")
    if any(row["action"] == "conflict" for row in report["files"]):
        raise ValueError(f"Existing map files need a merge. No map files were modified. See {report_file}")
    if not options.apply:
        print(report_file)
        return
    done = []
    try:
        for relative, target, old, new in changes:
            current = target.read_bytes() if target.is_file() else None
            if current != old:
                raise ValueError(f"Map changed while staging: {relative}")
            if old is not None:
                atomic_write(destination(out, "backup/" + relative), old)
            atomic_write(target, new)
            done.append((target, old))
        report["state"] = "staged"
        atomic_write(report_file, format_json(report).encode("utf-8"))
    except Exception:
        for target, old in reversed(done):
            if old is None:
                target.unlink()
            else:
                atomic_write(target, old)
        raise
    print(report_file)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle", type=Path, required=True)
    parser.add_argument("--map-copy", type=Path, required=True)
    parser.add_argument("--evidence", type=Path, required=True, help="New directory outside the map")
    parser.add_argument("--previous", type=Path, help="Successful stage-report.json for this map copy")
    parser.add_argument("--apply", action="store_true", help="Write only after inspecting a dry run and closing the copy in the editor")
    try:
        stage(parser.parse_args())
    except (BadZipFile, OSError, ValueError, KeyError, TypeError, RuntimeError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
